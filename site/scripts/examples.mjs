// Writes src/examples.gen.ts from the tested example contracts, so the page shows exactly the code
// `forge test` runs, with the imports a project that ran `forge install gtmcknight/judge` would use.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const site = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repo = path.dirname(site);
const FILES = ["PredictionMarket", "Bounty", "Job", "Grant", "Shoutout", "Contest", "Goal", "EggDare"];
const TESTS = { EggDare: "Dare" };

const body = (file) =>
  fs
    .readFileSync(file, "utf8")
    .replace(/^\/\/ SPDX-License-Identifier: MIT\npragma solidity \^0\.8\.20;\n\n/, "")
    .replace('from "../Judged.sol"', 'from "judge/Judged.sol"')
    .replace('from "../../src/JudgedTest.sol"', 'from "judge/JudgedTest.sol"')
    .replace(/from "\.\.\/\.\.\/src\/examples\/(\w+)\.sol"/, 'from "../src/$1.sol"')
    .trimEnd()
    .split("\n");

const out = {};
for (const name of FILES) {
  const contract = body(path.join(repo, "src/examples", `${name}.sol`));
  const test = body(path.join(repo, "test/examples", `${TESTS[name] ?? name}.t.sol`));
  out[name] = { contract, test, needsOpenZeppelin: contract.some((line) => line.includes("@openzeppelin")) };
}
const text = `// Generated by scripts/examples.mjs from src/examples and test/examples. Don't edit by hand.\n\nexport const EXAMPLE_CODE = ${JSON.stringify(out, null, 2)} as const;\n`;
fs.writeFileSync(path.join(site, "src/examples.gen.ts"), text);
console.log(`wrote ${FILES.length} examples into src/examples.gen.ts`);
